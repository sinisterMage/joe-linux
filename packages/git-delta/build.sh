# Not in the book: the newest upstream release, built with cargo as its
# Makefile (build, shell-completion) does, against the system's libgit2,
# Oniguruma and zlib. Upstream publishes no checksum for the source
# archive.
build() {
    # Keep cargo's registry and download cache inside the build directory
    # rather than in root's home in the shared build root.
    export CARGO_HOME="$PWD/.cargo-home"
    # Link the libgit2 and Oniguruma that pkg-config finds rather than
    # building the copies inside libgit2-sys and onig_sys. libz-sys uses the
    # system zlib by itself.
    export LIBGIT2_NO_VENDOR=1
    export RUSTONIG_SYSTEM_LIBONIG=1
    # --locked: build exactly the crate versions in upstream's Cargo.lock.
    cargo build --release --locked

    # Shell completions, generated by delta itself as the Makefile's
    # shell-completion target does. Upstream has no manual page.
    local delta=target/release/delta shell
    for shell in bash zsh fish; do
        "$delta" --generate-completion "$shell" > "delta.$shell"
    done
}

package() {
    install -Dm755 target/release/delta "$DESTDIR/usr/bin/delta"
    install -Dm644 delta.bash "$DESTDIR/usr/share/bash-completion/completions/delta"
    install -Dm644 delta.zsh "$DESTDIR/usr/share/zsh/site-functions/_delta"
    install -Dm644 delta.fish "$DESTDIR/usr/share/fish/vendor_completions.d/delta.fish"
}
