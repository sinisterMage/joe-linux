# Not in the book: the newest upstream release, built as its
# .goreleaser.yaml builds it, from the modules vendored in the archive.
# Delve does not need cgo on linux/amd64, but upstream leaves it on for
# native builds there because it enables the eBPF tracing backend
# (dlv trace --ebpf); so does this recipe. d116177d... is the commit the
# v1.27.2 tag points to, stamped into main.Build as goreleaser does.
build() {
    # Keep Go's build cache inside the build directory, out of the shared
    # build root's /root; never fetch another Go toolchain.
    export GOPATH="$PWD/.gopath"
    export GOMODCACHE="$PWD/.gopath/pkg/mod"
    export GOCACHE="$PWD/.gocache"
    export GOTOOLCHAIN=local GOTELEMETRY=off
    export GOFLAGS="-mod=vendor -trimpath -buildmode=pie"
    export CGO_ENABLED=1
    go build -ldflags "-X main.Build=d116177dd925e085ba5dd340f8c644f4a1501a3b" \
        -o dlv ./cmd/dlv

    # Shell completions, generated by dlv itself. dlv writes a default
    # config.yml on every start if there is none, so point it at a scratch
    # directory rather than the build root's /root. Upstream's documentation
    # is Markdown only; there is no manual page.
    local shell
    for shell in bash zsh fish; do
        XDG_CONFIG_HOME="$PWD/.config" ./dlv completion "$shell" > "dlv.$shell"
    done
}

package() {
    install -Dm755 dlv "$DESTDIR/usr/bin/dlv"
    install -Dm644 dlv.bash "$DESTDIR/usr/share/bash-completion/completions/dlv"
    install -Dm644 dlv.zsh "$DESTDIR/usr/share/zsh/site-functions/_dlv"
    install -Dm644 dlv.fish "$DESTDIR/usr/share/fish/vendor_completions.d/dlv.fish"
}
