# Not in the book: the newest upstream release, built with cargo as its
# Makefile does (default features: jemalloc and completions). Upstream
# publishes no checksum for the source archive.
build() {
    # Keep cargo's registry and download cache inside the build directory
    # rather than in root's home in the shared build root.
    export CARGO_HOME="$PWD/.cargo-home"
    # jemalloc, fd's allocator, has no recipe: tikv-jemalloc-sys builds the
    # copy it carries (with make) and links it in statically.
    # --locked: build exactly the crate versions in upstream's Cargo.lock.
    cargo build --release --locked

    # Bash and fish completions generated by fd itself, as the Makefile's
    # completions target does; the zsh one is hand-written in contrib/.
    local fd=target/release/fd
    "$fd" --gen-completions bash > fd.bash
    "$fd" --gen-completions fish > fd.fish
}

package() {
    install -Dm755 target/release/fd "$DESTDIR/usr/bin/fd"
    install -Dm644 doc/fd.1 "$DESTDIR/usr/share/man/man1/fd.1"
    install -Dm644 fd.bash "$DESTDIR/usr/share/bash-completion/completions/fd"
    install -Dm644 contrib/completion/_fd "$DESTDIR/usr/share/zsh/site-functions/_fd"
    install -Dm644 fd.fish "$DESTDIR/usr/share/fish/vendor_completions.d/fd.fish"
}
