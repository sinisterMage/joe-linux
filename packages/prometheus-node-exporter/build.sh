# Not in the book: the newest upstream release, built as its Makefile and
# .promu.yml build it (promu only runs go build with the flags below; it is
# not used because it would download itself).

# Commit and time of the v1.12.1 tag, for the version information that
# "node_exporter --version" and the build_info metric report.
_revision=6044da783597cc3b57aef7580ddcdcff58a4ee99
_date=20260714-12:04:06

build() {
    # Keep Go's module and build caches inside the build directory, out of
    # the shared build root's /root; never fetch another Go toolchain.
    export GOPATH="$PWD/.gopath"
    export GOMODCACHE="$PWD/.gopath/pkg/mod"
    export GOCACHE="$PWD/.gocache"
    export GOTOOLCHAIN=local GOTELEMETRY=off
    export GOFLAGS="-mod=readonly -modcacherw -trimpath -buildmode=pie"
    export CGO_ENABLED=0

    go build -ldflags "-X github.com/prometheus/common/version.Version=$PKG_VERSION
        -X github.com/prometheus/common/version.Revision=$_revision
        -X github.com/prometheus/common/version.Branch=HEAD
        -X github.com/prometheus/common/version.BuildUser=joe
        -X github.com/prometheus/common/version.BuildDate=$_date" \
        -o node_exporter .

    # The manual page, generated by the command-line parser (kingpin's
    # hidden --help-man flag).
    ./node_exporter --help-man > node_exporter.1
}

package() {
    # Upstream's name for the program, which its example units use.
    install -Dm755 node_exporter "$DESTDIR/usr/bin/node_exporter"
    install -Dm644 node_exporter.1 "$DESTDIR/usr/share/man/man1/node_exporter.1"

    # Options for the service: upstream's example (sysconfig.node_exporter),
    # which reads *.prom files from the textfile collector's directory.
    install -d "$DESTDIR/etc/default"
    cat > "$DESTDIR/etc/default/node_exporter" << "EOF2"
# Options for node_exporter.service; see node_exporter --help.
OPTIONS="--collector.textfile.directory /var/lib/node_exporter/textfile_collector"
EOF2

    # The unprivileged account upstream's units run node_exporter as, and
    # the textfile collector's directory (/var is not packaged).
    install -d "$DESTDIR/usr/lib/sysusers.d" "$DESTDIR/usr/lib/tmpfiles.d"
    cat > "$DESTDIR/usr/lib/sysusers.d/prometheus-node-exporter.conf" << "EOF2"
g node_exporter 67
u node_exporter 67:67 "Prometheus node exporter" /var/lib/node_exporter /usr/bin/false
EOF2
    cat > "$DESTDIR/usr/lib/tmpfiles.d/prometheus-node-exporter.conf" << "EOF2"
d /var/lib/node_exporter 0755 node_exporter node_exporter -
d /var/lib/node_exporter/textfile_collector 0755 node_exporter node_exporter -
EOF2

    # Upstream's example units (examples/systemd): the socket listens on
    # port 9100 and starts the exporter, which takes the socket from
    # systemd. Two changes: the program's path, and /etc/default for
    # /etc/sysconfig. Neither unit is enabled.
    install -d "$DESTDIR/usr/lib/systemd/system"
    sed -e 's|/usr/sbin/node_exporter|/usr/bin/node_exporter|' \
        -e 's|/etc/sysconfig/node_exporter|/etc/default/node_exporter|' \
        examples/systemd/node_exporter.service \
        > "$DESTDIR/usr/lib/systemd/system/node_exporter.service"
    grep -q '^ExecStart=/usr/bin/node_exporter ' "$DESTDIR/usr/lib/systemd/system/node_exporter.service"
    grep -q '^EnvironmentFile=-/etc/default/node_exporter$' "$DESTDIR/usr/lib/systemd/system/node_exporter.service"
    install -m644 examples/systemd/node_exporter.socket "$DESTDIR/usr/lib/systemd/system/"
}
