# Not in the book: the newest upstream release, built with cargo as
# upstream's release builds do (the uv package, release profile).
build() {
    # Keep cargo's registry and download cache inside the build directory
    # rather than in root's home in the shared build root.
    export CARGO_HOME="$PWD/.cargo-home"
    # The system libzstd rather than the copy in zstd-sys.
    export ZSTD_SYS_USE_PKG_CONFIG=1
    # AWS-LC (rustls's crypto provider) has no recipe: aws-lc-sys builds
    # its bundled copy with cc rather than CMake, and does not look for an
    # installed one. jemalloc, which uv uses as its allocator, is likewise
    # built from the copy in tikv-jemalloc-sys (with make).
    export AWS_LC_SYS_USE_SYSTEM=0
    export AWS_LC_SYS_CMAKE_BUILDER=0
    # --locked: build exactly the crate versions in upstream's Cargo.lock.
    # The uv package holds both programs, uv and uvx.
    cargo build --release --locked -p uv

    # Shell completions, generated by the programs themselves as uv's
    # installation guide describes.
    local uv=target/release/uv uvx=target/release/uvx shell
    for shell in bash zsh fish; do
        "$uv" generate-shell-completion "$shell" > "uv.$shell"
        "$uvx" --generate-shell-completion "$shell" > "uvx.$shell"
    done
}

package() {
    install -Dm755 target/release/uv "$DESTDIR/usr/bin/uv"
    install -Dm755 target/release/uvx "$DESTDIR/usr/bin/uvx"
    local name
    for name in uv uvx; do
        install -Dm644 "$name.bash" "$DESTDIR/usr/share/bash-completion/completions/$name"
        install -Dm644 "$name.zsh" "$DESTDIR/usr/share/zsh/site-functions/_$name"
        install -Dm644 "$name.fish" "$DESTDIR/usr/share/fish/vendor_completions.d/$name.fish"
    done
}
