# Not in the book: the newest upstream release, built as its Makefile and
# release helper (bin/cross-compile.go) build it, from upstream's vendored
# modules, so no network is needed.
prepare() {
    tar -xf "$SOURCES/rclone-v1.76.0-vendor.tar.gz"
    test -f vendor/modules.txt
}

build() {
    # Keep Go's build cache inside the build directory, out of the shared
    # build root's /root; never fetch another Go toolchain.
    export GOPATH="$PWD/.gopath"
    export GOCACHE="$PWD/.gocache"
    export GOTOOLCHAIN=local GOTELEMETRY=off GOPROXY=off
    export GOFLAGS="-mod=vendor -trimpath -buildmode=pie"
    export CGO_ENABLED=0
    # noselfupdate: the package manager, not "rclone selfupdate", replaces
    # this binary. The version stamp is the Makefile's; without it rclone
    # calls itself v1.76.0-DEV.
    go build -tags noselfupdate \
        -ldflags "-s -X github.com/rclone/rclone/fs.Version=v$PKG_VERSION" \
        -o rclone .

    # Shell completions, generated by rclone itself; HOME is kept away from
    # the build root so that no configuration is looked for there.
    mkdir completions .home
    HOME="$PWD/.home" ./rclone completion bash completions/rclone.bash
    HOME="$PWD/.home" ./rclone completion zsh completions/_rclone
    HOME="$PWD/.home" ./rclone completion fish completions/rclone.fish
}

package() {
    install -Dm755 rclone "$DESTDIR/usr/bin/rclone"
    # The manual page upstream generated for the release.
    install -Dm644 rclone.1 "$DESTDIR/usr/share/man/man1/rclone.1"
    install -Dm644 completions/rclone.bash "$DESTDIR/usr/share/bash-completion/completions/rclone"
    install -Dm644 completions/_rclone "$DESTDIR/usr/share/zsh/site-functions/_rclone"
    install -Dm644 completions/rclone.fish "$DESTDIR/usr/share/fish/vendor_completions.d/rclone.fish"
    # "mount -t rclone" and fstab entries find the helper by this name, as
    # rclone's mount documentation asks.
    install -d "$DESTDIR/usr/sbin"
    ln -s ../bin/rclone "$DESTDIR/usr/sbin/mount.rclone"
}
