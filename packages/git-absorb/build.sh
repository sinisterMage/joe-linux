# Not in the book: the newest upstream release, built with cargo as its
# README describes, against the system's libgit2 and zlib. Upstream
# publishes no checksum for the source archive.
build() {
    # Keep cargo's registry and download cache inside the build directory
    # rather than in root's home in the shared build root.
    export CARGO_HOME="$PWD/.cargo-home"
    # Link the libgit2 that pkg-config finds rather than building the copy
    # inside libgit2-sys. libz-sys uses the system zlib by itself.
    export LIBGIT2_NO_VENDOR=1
    # --locked: build exactly the crate versions in upstream's Cargo.lock.
    cargo build --release --locked

    # Shell completions, generated by git-absorb itself as its README
    # describes.
    local absorb=target/release/git-absorb shell
    for shell in bash zsh fish; do
        "$absorb" --gen-completions "$shell" > "git-absorb.$shell"
    done

    # The manual page from its AsciiDoc source. Documentation/Makefile uses
    # AsciiDoc's a2x, which has no recipe; Asciidoctor reads the same source.
    asciidoctor -b manpage -d manpage \
        -a man-version="$PKG_VERSION" \
        -a mansource=git-absorb \
        -a manversion="$PKG_VERSION" \
        -a manmanual="git absorb" \
        -o git-absorb.1 Documentation/git-absorb.adoc
}

package() {
    install -Dm755 target/release/git-absorb "$DESTDIR/usr/bin/git-absorb"
    install -Dm644 git-absorb.1 "$DESTDIR/usr/share/man/man1/git-absorb.1"
    install -Dm644 git-absorb.bash "$DESTDIR/usr/share/bash-completion/completions/git-absorb"
    install -Dm644 git-absorb.zsh "$DESTDIR/usr/share/zsh/site-functions/_git-absorb"
    install -Dm644 git-absorb.fish "$DESTDIR/usr/share/fish/vendor_completions.d/git-absorb.fish"
}
