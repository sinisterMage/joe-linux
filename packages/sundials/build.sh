# Not in the book: upstream stable, following its CMake instructions.
# Double precision with 64-bit sunindextype (Octave index ABI), LP64 BLAS.
# Serial, OpenMP, pthread, KLU and LAPACK solvers; distributed/GPU stacks are not packaged.
build() {
    cmake -S . -B build -G Ninja \
        -DCMAKE_BUILD_TYPE=Release -DCMAKE_INSTALL_PREFIX=/usr \
        -DCMAKE_INSTALL_LIBDIR=lib \
        -DBUILD_SHARED_LIBS=ON -DBUILD_STATIC_LIBS=OFF \
        -DSUNDIALS_PRECISION=DOUBLE -DSUNDIALS_INDEX_SIZE=64 \
        -DSUNDIALS_ENABLE_FORTRAN=ON -DFortran_INSTALL_MODDIR=include/sundials \
        -DSUNDIALS_ENABLE_PYTHON=OFF -DSUNDIALS_ENABLE_OPENMP=ON \
        -DSUNDIALS_ENABLE_PTHREAD=ON -DSUNDIALS_ENABLE_KLU=ON \
        -DKLU_INCLUDE_DIR=/usr/include/suitesparse -DKLU_LIBRARY_DIR=/usr/lib \
        -DSUNDIALS_ENABLE_LAPACK=ON -DBLA_VENDOR=Generic \
        '-DLAPACK_LIBRARIES=/usr/lib/liblapack.so;/usr/lib/libopenblas.so' \
        -DSUNDIALS_ENABLE_C_EXAMPLES=OFF -DSUNDIALS_ENABLE_CXX_EXAMPLES=OFF \
        -DSUNDIALS_ENABLE_FORTRAN_EXAMPLES=OFF -DSUNDIALS_ENABLE_EXAMPLES_INSTALL=OFF \
        -DSUNDIALS_TEST_ENABLE_UNIT_TESTS=OFF -DSUNDIALS_TEST_ENABLE_DEV_TESTS=OFF \
        -DSUNDIALS_ENABLE_MPI=OFF \
        -DSUNDIALS_ENABLE_OPENMP_DEVICE=OFF \
        -DSUNDIALS_ENABLE_CUDA=OFF \
        -DSUNDIALS_ENABLE_HIP=OFF \
        -DSUNDIALS_ENABLE_SYCL=OFF \
        -DSUNDIALS_ENABLE_GINKGO=OFF \
        -DSUNDIALS_ENABLE_HYPRE=OFF \
        -DSUNDIALS_ENABLE_KOKKOS=OFF \
        -DSUNDIALS_ENABLE_KOKKOS_KERNELS=OFF \
        -DSUNDIALS_ENABLE_MAGMA=OFF \
        -DSUNDIALS_ENABLE_ONEMKL=OFF \
        -DSUNDIALS_ENABLE_PETSC=OFF \
        -DSUNDIALS_ENABLE_RAJA=OFF \
        -DSUNDIALS_ENABLE_SUPERLUDIST=OFF \
        -DSUNDIALS_ENABLE_SUPERLUMT=OFF \
        -DSUNDIALS_ENABLE_TRILINOS=OFF \
        -DSUNDIALS_ENABLE_XBRAID=OFF \
        -DSUNDIALS_ENABLE_ADIAK=OFF \
        -DSUNDIALS_ENABLE_CALIPER=OFF
    cmake --build build -j"$JOBS"
}

package() {
    DESTDIR="$DESTDIR" cmake --install build
}
