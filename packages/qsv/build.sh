# Not in the book: upstream's newest release that joe's Rust can build.
# qsv 29.0.0 (2026-11-15) needs Rust 1.100 and joe has 1.99; 28.0.0 needs
# 1.99. Built with cargo as upstream's own Debian package is: the qsv binary
# with the "feature_capable" and "get" features, plus the default jemalloc
# allocator. Not enabled, though pure Rust: apply, fetch, foreach, geocode,
# luau, polars, profile, readstat, synthesize, to and viz (each a large
# dependency tree, polars above all); not enabled because they need
# what joe does not have or want: python (embeds libpython), ui (clipboard,
# terminal and file-dialog libraries), magika (ONNX Runtime) and
# self_update. Upstream publishes no checksum for the source archive.
build() {
    # Keep cargo's registry, git checkouts and download cache inside the
    # build directory rather than in root's home in the shared build root.
    export CARGO_HOME="$PWD/.cargo-home"
    # Link the system libzstd that pkg-config finds rather than building
    # the copy inside the zstd-sys crate.
    export ZSTD_SYS_USE_PKG_CONFIG=1
    # --locked: build exactly the crate versions in upstream's Cargo.lock.
    cargo build --release --locked --bin qsv --features feature_capable,get
}

package() {
    install -Dm755 target/release/qsv "$DESTDIR/usr/bin/qsv"

    # Shell completions, generated by upstream from the commands' usage
    # text and shipped in the source.
    local c=contrib/completions/examples
    install -Dm644 "$c/qsv.bash" "$DESTDIR/usr/share/bash-completion/completions/qsv"
    install -Dm644 "$c/qsv.zsh" "$DESTDIR/usr/share/zsh/site-functions/_qsv"
    install -Dm644 "$c/qsv.fish" "$DESTDIR/usr/share/fish/vendor_completions.d/qsv.fish"
}
