# Not in the book: the newest upstream release, built with cargo as its
# README describes, with upstream's default features (TLS through rustls).
build() {
    # Keep cargo's registry and download cache inside the build directory
    # rather than in root's home in the shared build root.
    export CARGO_HOME="$PWD/.cargo-home"
    # Link the system libzstd that pkg-config finds rather than building
    # the copy inside the zstd-sys crate.
    export ZSTD_SYS_USE_PKG_CONFIG=1
    # --locked: build exactly the crate versions in upstream's Cargo.lock.
    cargo build --release --locked

    # The manual page and shell completions, generated by miniserve itself.
    local m=target/release/miniserve
    "$m" --print-manpage > miniserve.1
    "$m" --print-completions bash > miniserve.bash
    "$m" --print-completions zsh > _miniserve
    "$m" --print-completions fish > miniserve.fish
}

package() {
    install -Dm755 target/release/miniserve "$DESTDIR/usr/bin/miniserve"
    install -Dm644 miniserve.1 "$DESTDIR/usr/share/man/man1/miniserve.1"
    install -Dm644 miniserve.bash "$DESTDIR/usr/share/bash-completion/completions/miniserve"
    install -Dm644 _miniserve "$DESTDIR/usr/share/zsh/site-functions/_miniserve"
    install -Dm644 miniserve.fish "$DESTDIR/usr/share/fish/vendor_completions.d/miniserve.fish"
    # Upstream's template unit (miniserve@-srv-www.service serves /srv/www
    # to localhost as a dynamic user). Not enabled.
    install -Dm644 packaging/miniserve@.service "$DESTDIR/usr/lib/systemd/system/miniserve@.service"
}
