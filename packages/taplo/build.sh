# Not in the book: the newest upstream release of the taplo CLI, built
# with cargo as its release workflow builds it (cargo build --release --bin
# taplo, default features: completions, lint, lsp, rustls-tls). Upstream
# publishes no checksum for the source archive.
#
# The native-tls feature (system OpenSSL) is not used: the openssl-sys in
# upstream's Cargo.lock (0.9.103) refuses OpenSSL 4, so TLS for fetching
# schemas stays rustls with ring, as in upstream's binaries.
build() {
    # Keep cargo's registry and download cache inside the build directory
    # rather than in root's home in the shared build root.
    export CARGO_HOME="$PWD/.cargo-home"
    # --locked: build exactly the crate versions in upstream's Cargo.lock.
    cargo build --release --locked -p taplo-cli --bin taplo

    # Shell completions, generated by taplo itself. Upstream has no manual
    # page.
    local taplo=target/release/taplo shell
    for shell in bash zsh fish; do
        "$taplo" completions "$shell" > "taplo.$shell"
    done
}

package() {
    install -Dm755 target/release/taplo "$DESTDIR/usr/bin/taplo"
    install -Dm644 taplo.bash "$DESTDIR/usr/share/bash-completion/completions/taplo"
    install -Dm644 taplo.zsh "$DESTDIR/usr/share/zsh/site-functions/_taplo"
    install -Dm644 taplo.fish "$DESTDIR/usr/share/fish/vendor_completions.d/taplo.fish"
}
