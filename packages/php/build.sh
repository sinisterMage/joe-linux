# Following the book's PHP page: the command line interpreter, php-fpm (its
# systemd unit shipped, not enabled), php-cgi and phpdbg, with every
# extension built into them. No Apache module (Apache has no recipe) and no
# PEAR. The configuration is the production php.ini in /etc/php.ini.
build() {
    # The book's options, except that DBA is built in like the rest rather
    # than as a module php.ini would have to load, and the FPM pool runs as
    # its own account (php-fpm) rather than Apache's.
    #
    # Added, because their libraries have recipes: OpenSSL, curl, SQLite and
    # PDO SQLite (on by default), mbstring with its regular expressions
    # (Oniguruma; the book turns them off for want of it), intl (ICU),
    # sodium, Argon2 password hashing (libargon2), zip (libzip), the
    # bundled GD with the system's JPEG, PNG, WebP, AVIF and FreeType
    # libraries, XSL (libxslt), Enchant, FFI (libffi; usable only from the
    # command line and preloaded scripts, ffi.enable=preload), LMDB in DBA,
    # the system's PCRE2, ACLs on the FPM socket, and the extensions that
    # need no library: EXIF, sockets, pcntl, shmop, System V IPC, SOAP, and
    # MySQLi and PDO MySQL through PHP's own MySQL driver (mysqlnd).
    #
    # Off: PostgreSQL (pgsql, pdo_pgsql), because the postgresql recipe is
    # not split and the client library would bring the whole server; LDAP
    # (OpenLDAP has no recipe); XPM in GD (it would tie PHP to Xlib);
    # libedit (no recipe; readline is used); tidy, SNMP, ODBC, Firebird,
    # FreeTDS, QDBM, Berkeley DB, Tokyo Cabinet, mm, Capstone and Valgrind
    # (no recipes); DTrace; the external libgd and uriparser (no recipes:
    # the bundled copies are built).
    ./configure --prefix=/usr \
        --sysconfdir=/etc \
        --localstatedir=/var \
        --datadir=/usr/share/php \
        --mandir=/usr/share/man \
        --enable-fpm \
        --without-pear \
        --with-fpm-user=php-fpm \
        --with-fpm-group=php-fpm \
        --with-fpm-systemd \
        --with-fpm-acl \
        --with-config-file-path=/etc \
        --with-zlib \
        --enable-bcmath \
        --with-bz2 \
        --enable-calendar \
        --enable-dba \
        --with-gdbm \
        --with-lmdb \
        --without-qdbm \
        --without-db4 \
        --without-tcadb \
        --with-gmp \
        --enable-ftp \
        --with-gettext \
        --enable-mbstring \
        --enable-mbregex \
        --with-readline \
        --without-libedit \
        --with-openssl \
        --with-external-pcre \
        --with-curl \
        --with-sqlite3 \
        --with-pdo-sqlite \
        --enable-intl \
        --with-sodium \
        --with-password-argon2 \
        --with-zip \
        --enable-gd \
        --with-jpeg \
        --with-webp \
        --with-avif \
        --with-freetype \
        --without-xpm \
        --with-xsl \
        --with-enchant \
        --with-ffi \
        --enable-exif \
        --enable-sockets \
        --enable-pcntl \
        --enable-shmop \
        --enable-sysvmsg \
        --enable-sysvsem \
        --enable-sysvshm \
        --enable-soap \
        --enable-mysqlnd \
        --with-mysqli \
        --with-pdo-mysql \
        --with-mysql-sock=/run/mysqld/mysqld.sock \
        --without-pgsql \
        --without-pdo-pgsql \
        --without-ldap \
        --without-tidy \
        --without-snmp \
        --without-unixODBC \
        --without-iodbc \
        --without-pdo-odbc \
        --without-pdo-firebird \
        --without-pdo-dblib \
        --without-mm \
        --without-capstone \
        --without-valgrind \
        --disable-dtrace
    make
}

package() {
    # PHP stages into INSTALL_ROOT, not DESTDIR.
    make INSTALL_ROOT="$DESTDIR" install
    install -v -m644 php.ini-production "$DESTDIR/etc/php.ini"

    # The book's renames: the FPM configuration as installed is upstream's
    # default.
    mv -v "$DESTDIR"/etc/php-fpm.conf{.default,}
    mv -v "$DESTDIR"/etc/php-fpm.d/www.conf{.default,}

    # Upstream's unit, generated by configure (Type=notify, the paths
    # above). It is not enabled.
    install -Dm644 sapi/fpm/php-fpm.service "$DESTDIR/usr/lib/systemd/system/php-fpm.service"

    # The account FPM's pool (www.conf) runs scripts as; the master stays
    # root. It logs to /var/log/php-fpm.log and keeps its PID file in
    # /run, both of which exist.
    install -d "$DESTDIR/usr/lib/sysusers.d"
    cat > "$DESTDIR/usr/lib/sysusers.d/php-fpm.conf" << "EOT"
g php-fpm 89
u php-fpm 89:89 "PHP FastCGI Process Manager pool" - /usr/bin/false
EOT
}
