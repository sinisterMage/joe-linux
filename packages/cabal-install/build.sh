# Not in the book: upstream's bootstrap for systems with no cabal yet
# (bootstrap/README.md, including its "Offline build"). bootstrap.py builds
# cabal-install and the libraries it needs one by one with Cabal's Setup.hs,
# exactly as bootstrap/linux-9.12.4.json plans them for GHC 9.12.4: which
# packages come with GHC (it checks they are installed), and the version,
# .cabal revision, checksum and flags of every package taken from Hackage.
# Those are all sources of this recipe, so nothing is downloaded.

_cabal_ghc_version=9.12.4

_cabal_env() {
    # Cabal reads and writes UTF-8 package descriptions; the build sandbox's
    # POSIX locale makes it fail on the first non-ASCII character.
    export LANG=C.UTF-8 LC_ALL=C.UTF-8
    # Keep cabal's configuration and caches out of the shared build root.
    export HOME="$PWD/.home" CABAL_DIR="$PWD/.cabal"
}

prepare() {
    # bootstrap.py looks for each Hackage package as
    # _build/tarballs/NAME-VERSION.tar.gz and for its revised .cabal file as
    # _build/tarballs/NAME.cabal, and fetches only what is not there. The
    # plan names the files; package.zon lists them under the same names.
    mkdir -p .home _build/tarballs
    python3 - "bootstrap/linux-$_cabal_ghc_version.json" "$SOURCES" _build/tarballs << "EOF"
import json, shutil, sys

plan, sources, dest = sys.argv[1:]
for dep in json.load(open(plan))["dependencies"]:
    if dep["source"] != "hackage":
        continue
    name, version, revision = dep["package"], dep["version"], dep["revision"]
    shutil.copyfile(f"{sources}/hackage-{name}-{version}.tar.gz",
                    f"{dest}/{name}-{version}.tar.gz")
    if revision is not None:
        shutil.copyfile(f"{sources}/hackage-{name}-{version}-r{revision}.cabal",
                        f"{dest}/{name}.cabal")
EOF
}

build() {
    _cabal_env
    # From the top of the source tree, where it finds the local packages
    # (Cabal, cabal-install and the rest). --no-archive: no tarball of the
    # result for other machines.
    python3 bootstrap/bootstrap.py \
        -d "bootstrap/linux-$_cabal_ghc_version.json" \
        -w /usr/bin/ghc \
        -j "$JOBS" \
        --no-archive
}

package() {
    _cabal_env
    install -Dm755 _build/bin/cabal "$DESTDIR/usr/bin/cabal"
    install -Dm644 cabal-install/bash-completion/cabal \
        "$DESTDIR/usr/share/bash-completion/completions/cabal"
    # The man page is generated by cabal itself from its command
    # descriptions; --raw prints the roff source instead of showing it.
    install -d "$DESTDIR/usr/share/man/man1"
    _build/bin/cabal man --raw > "$DESTDIR/usr/share/man/man1/cabal.1"
}
