# Not in the book: built as upstream's README says (build/gen.py, then
# ninja), with GCC, as Debian builds it.
build() {
    # gen.py would use clang unless told; it is GCC here, like every other
    # C++ program. --allow-warnings: upstream builds with -Werror for its
    # own compiler, and a newer GCC's new warnings should not fail the
    # build. libstdc++ is the shared one, as for everything else.
    CXX=g++ AR=ar python3 build/gen.py \
        --allow-warnings \
        --no-static-libstdc++

    # gen.py takes the commit position from git describe, and the tarball
    # has no .git; it has written a dummy header ("0 (UNKNOWN)"). This is
    # what it would have written in a clone of that commit.
    cat > out/last_commit_position.h << "EOT"
// Generated by build/gen.py.

#ifndef OUT_LAST_COMMIT_POSITION_H_
#define OUT_LAST_COMMIT_POSITION_H_

#define LAST_COMMIT_POSITION_NUM 2615
#define LAST_COMMIT_POSITION "2615 (2e3ba8239556)"

#endif  // OUT_LAST_COMMIT_POSITION_H_
EOT

    ninja -C out gn
}

package() {
    install -Dm755 out/gn "$DESTDIR/usr/bin/gn"

    # Vim support (syntax, file type detection, gf to BUILD.gn files), in
    # the directory Vim searches for system-wide additions.
    local d
    for d in autoload ftdetect ftplugin syntax; do
        install -Dm644 -t "$DESTDIR/usr/share/vim/vimfiles/$d" misc/vim/$d/*.vim
    done
}
