# Not in the book: the newest upstream release, built with cargo as
# upstream's release builds do (the ruff package, release profile).
build() {
    # Keep cargo's registry and download cache inside the build directory
    # rather than in root's home in the shared build root.
    export CARGO_HOME="$PWD/.cargo-home"
    # --locked: build exactly the crate versions in upstream's Cargo.lock.
    # Only the ruff package: the workspace also holds ty and development
    # tools. jemalloc, ruff's allocator on Linux, is built from the copy in
    # tikv-jemalloc-sys (with make); zlib comes from the pure-Rust zlib-rs.
    cargo build --release --locked -p ruff

    # Shell completions, generated by ruff itself as its documentation
    # describes.
    local shell
    for shell in bash zsh fish; do
        target/release/ruff generate-shell-completion "$shell" > "ruff.$shell"
    done
}

package() {
    install -Dm755 target/release/ruff "$DESTDIR/usr/bin/ruff"
    install -Dm644 ruff.bash "$DESTDIR/usr/share/bash-completion/completions/ruff"
    install -Dm644 ruff.zsh "$DESTDIR/usr/share/zsh/site-functions/_ruff"
    install -Dm644 ruff.fish "$DESTDIR/usr/share/fish/vendor_completions.d/ruff.fish"
}
