# Not in the book: the newest upstream release, built as its Makefile and
# .promu.yml build it ("make build" runs "make assets assets-compress" and
# then promu, which only runs go build with the tags and flags below). promu
# itself is not used: it would download itself.
#
# The web UI is built from source: upstream's "make assets" installs the
# npm packages with pnpm from web/ui/pnpm-lock.yaml (and, for the classic
# UI, web/ui/react-app/pnpm-lock.yaml) and builds the two codemirror
# modules, the classic React app (--enable-feature=old-ui) and the current
# Mantine UI. scripts/compress_assets.sh gzips them into web/ui/static and
# writes web/ui/embed.go, which the builtinassets tag compiles in. Some of
# the tools pnpm installs for the build (rolldown and rollup, Lightning CSS,
# the native TypeScript compiler, ...) are npm packages carrying prebuilt
# native binaries; they run only while building, and nothing of them is
# installed.

# Commit and time of the v3.16.0 tag, for the version information that
# "prometheus --version" and the build_info metric report.
_revision=e2e28adeee2c5883d000fc82aca6008cfbf7e96d
_date=20261105-15:07:18

build() {
    # Keep Go's caches and pnpm's store, cache and configuration inside the
    # build directory, out of the shared build root's /root; never fetch
    # another Go toolchain.
    export HOME="$PWD/.home"
    export XDG_CACHE_HOME="$HOME/.cache" XDG_DATA_HOME="$HOME/.local/share"
    export XDG_CONFIG_HOME="$HOME/.config" XDG_STATE_HOME="$HOME/.local/state"
    export GOPATH="$PWD/.gopath"
    export GOMODCACHE="$PWD/.gopath/pkg/mod"
    export GOCACHE="$PWD/.gocache"
    export GOTOOLCHAIN=local GOTELEMETRY=off
    export GOFLAGS="-mod=readonly -modcacherw -trimpath -buildmode=pie"
    export CGO_ENABLED=0

    # The web UI ("make ui-install ui-build"). --frozen-lockfile: install
    # exactly the versions in upstream's lockfiles. CI="" keeps the classic
    # app's build from turning lint warnings into errors, as the Makefile
    # does.
    (cd web/ui && pnpm install --frozen-lockfile)
    (cd web/ui/react-app && pnpm install --frozen-lockfile)
    (cd web/ui && CI="" pnpm run build)
    scripts/compress_assets.sh

    local ldflags="-X github.com/prometheus/common/version.Version=$PKG_VERSION
        -X github.com/prometheus/common/version.Revision=$_revision
        -X github.com/prometheus/common/version.Branch=HEAD
        -X github.com/prometheus/common/version.BuildUser=joe
        -X github.com/prometheus/common/version.BuildDate=$_date"
    go build -tags netgo,builtinassets -ldflags "$ldflags" -o prometheus ./cmd/prometheus
    go build -tags netgo,builtinassets -ldflags "$ldflags" -o promtool ./cmd/promtool

    # Manual pages and completions, generated by the programs' command-line
    # parser (kingpin's hidden --help-man and --completion-script-* flags).
    ./prometheus --help-man > prometheus.1
    ./promtool --help-man > promtool.1
    ./promtool --completion-script-bash > promtool.bash
    ./promtool --completion-script-zsh > promtool.zsh
}

package() {
    install -Dm755 prometheus "$DESTDIR/usr/bin/prometheus"
    install -Dm755 promtool "$DESTDIR/usr/bin/promtool"
    install -Dm644 prometheus.1 "$DESTDIR/usr/share/man/man1/prometheus.1"
    install -Dm644 promtool.1 "$DESTDIR/usr/share/man/man1/promtool.1"
    install -Dm644 promtool.bash "$DESTDIR/usr/share/bash-completion/completions/promtool"
    install -Dm644 promtool.zsh "$DESTDIR/usr/share/zsh/site-functions/_promtool"

    # Upstream's example configuration, which scrapes Prometheus itself, as
    # the release tarball carries it.
    install -Dm644 documentation/examples/prometheus.yml "$DESTDIR/etc/prometheus/prometheus.yml"

    # Extra command-line options for the service.
    install -d "$DESTDIR/etc/default"
    cat > "$DESTDIR/etc/default/prometheus" << "EOF"
# Extra options for prometheus.service; see prometheus --help. The
# configuration file and the data directory are already given.
PROMETHEUS_ARGS=""
EOF

    # The account Prometheus runs as, and its data directory (/var is not
    # packaged).
    install -d "$DESTDIR/usr/lib/sysusers.d" "$DESTDIR/usr/lib/tmpfiles.d"
    cat > "$DESTDIR/usr/lib/sysusers.d/prometheus.conf" << "EOF"
g prometheus 60
u prometheus 60:60 "Prometheus monitoring system" /var/lib/prometheus /usr/bin/false
EOF
    cat > "$DESTDIR/usr/lib/tmpfiles.d/prometheus.conf" << "EOF"
d /var/lib/prometheus 0750 prometheus prometheus -
EOF

    # Upstream ships no unit. This one runs the server as its own user,
    # with its data in /var/lib/prometheus. Not enabled.
    install -d "$DESTDIR/usr/lib/systemd/system"
    cat > "$DESTDIR/usr/lib/systemd/system/prometheus.service" << "EOF"
[Unit]
Description=Prometheus monitoring system and time series database
Documentation=https://prometheus.io/docs/ man:prometheus(1)
Wants=network-online.target
After=network-online.target

[Service]
User=prometheus
Group=prometheus
EnvironmentFile=-/etc/default/prometheus
ExecStart=/usr/bin/prometheus --config.file=/etc/prometheus/prometheus.yml --storage.tsdb.path=/var/lib/prometheus/data $PROMETHEUS_ARGS
ExecReload=/usr/bin/kill -HUP $MAINPID
WorkingDirectory=/var/lib/prometheus
Restart=on-failure
TimeoutStopSec=600
LimitNOFILE=65536
NoNewPrivileges=yes
ProtectSystem=strict
ProtectHome=yes
PrivateTmp=yes
PrivateDevices=yes
ReadWritePaths=/var/lib/prometheus

[Install]
WantedBy=multi-user.target
EOF
}
