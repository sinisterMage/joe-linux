# Not in the book: the newest upstream release, built as its Makefile and
# .promu.yml build it ("make build" is "ui-elm ui-mantine" followed by
# promu, which only runs go build with the tags and flags below). promu
# itself is not used: it would download itself.
#
# Both web UIs are built from source with npm from upstream's lockfiles: the
# Elm UI in ui/app (vite with vite-plugin-elm) and the Mantine UI in
# ui/mantine-ui, whose generated protobuf code (src/gen) is committed, so
# buf is not needed. Both land in ui/app/dist, which ui/web.go embeds. Some
# of the tools npm installs for the build are npm packages carrying
# prebuilt native binaries: the Elm compiler itself (@elm_binaries/linux_x64,
# pinned with its hash in package-lock.json), elm-format,
# rolldown, Lightning CSS and the native TypeScript compiler. They run only
# while building, and nothing of them is installed.

# Commit and time of the v0.35.0 tag, for the version information that
# "alertmanager --version" and the build_info metric report.
_revision=8cf67a8e75004bad6c3c6bacc829945cf8a3ee65
_date=20261109-16:34:57

build() {
    # Keep Go's caches, npm's cache and Elm's package store (~/.elm) inside
    # the build directory, out of the shared build root's /root; never
    # fetch another Go toolchain.
    export HOME="$PWD/.home"
    export npm_config_cache="$HOME/.npm"
    export ELM_HOME="$HOME/.elm"
    export GOPATH="$PWD/.gopath"
    export GOMODCACHE="$PWD/.gopath/pkg/mod"
    export GOCACHE="$PWD/.gocache"
    export GOTOOLCHAIN=local GOTELEMETRY=off
    export GOFLAGS="-mod=readonly -modcacherw -trimpath -buildmode=pie"
    export CGO_ENABLED=0

    # "make ui-elm ui-mantine": npm ci, then the build, in each directory.
    make -C ui/app build
    make -C ui/mantine-ui build

    local ldflags="-X github.com/prometheus/common/version.Version=$PKG_VERSION
        -X github.com/prometheus/common/version.Revision=$_revision
        -X github.com/prometheus/common/version.Branch=HEAD
        -X github.com/prometheus/common/version.BuildUser=joe
        -X github.com/prometheus/common/version.BuildDate=$_date"
    go build -tags netgo -ldflags "$ldflags" -o alertmanager ./cmd/alertmanager
    go build -tags netgo -ldflags "$ldflags" -o amtool ./cmd/amtool

    # Manual pages and completions, generated by the programs' command-line
    # parser (kingpin's hidden --help-man and --completion-script-* flags).
    ./alertmanager --help-man > alertmanager.1
    ./amtool --help-man > amtool.1
    ./amtool --completion-script-bash > amtool.bash
    ./amtool --completion-script-zsh > amtool.zsh
}

package() {
    install -Dm755 alertmanager "$DESTDIR/usr/bin/alertmanager"
    install -Dm755 amtool "$DESTDIR/usr/bin/amtool"
    install -Dm644 alertmanager.1 "$DESTDIR/usr/share/man/man1/alertmanager.1"
    install -Dm644 amtool.1 "$DESTDIR/usr/share/man/man1/amtool.1"
    install -Dm644 amtool.bash "$DESTDIR/usr/share/bash-completion/completions/amtool"
    install -Dm644 amtool.zsh "$DESTDIR/usr/share/zsh/site-functions/_amtool"

    # The configuration upstream's release tarball carries
    # (examples/ha/alertmanager.yml): every alert goes to a webhook on
    # 127.0.0.1:5001.
    install -Dm644 examples/ha/alertmanager.yml "$DESTDIR/etc/alertmanager/alertmanager.yml"

    # Extra command-line options for the service.
    install -d "$DESTDIR/etc/default"
    cat > "$DESTDIR/etc/default/alertmanager" << "EOF"
# Extra options for alertmanager.service; see alertmanager --help. The
# configuration file and the data directory are already given. Alertmanager
# listens for its high-availability peers on port 9094 unless
# --cluster.listen-address= (empty) is given.
ALERTMANAGER_ARGS=""
EOF

    # The account Alertmanager runs as, and its data directory (silences
    # and the notification log; /var is not packaged).
    install -d "$DESTDIR/usr/lib/sysusers.d" "$DESTDIR/usr/lib/tmpfiles.d"
    cat > "$DESTDIR/usr/lib/sysusers.d/alertmanager.conf" << "EOF"
g alertmanager 65
u alertmanager 65:65 "Prometheus Alertmanager" /var/lib/alertmanager /usr/bin/false
EOF
    cat > "$DESTDIR/usr/lib/tmpfiles.d/alertmanager.conf" << "EOF"
d /var/lib/alertmanager 0750 alertmanager alertmanager -
EOF

    # Upstream ships no unit. This one runs Alertmanager as its own user,
    # with its data in /var/lib/alertmanager. Not enabled.
    install -d "$DESTDIR/usr/lib/systemd/system"
    cat > "$DESTDIR/usr/lib/systemd/system/alertmanager.service" << "EOF"
[Unit]
Description=Prometheus Alertmanager
Documentation=https://prometheus.io/docs/alerting/latest/alertmanager/ man:alertmanager(1)
Wants=network-online.target
After=network-online.target

[Service]
User=alertmanager
Group=alertmanager
EnvironmentFile=-/etc/default/alertmanager
ExecStart=/usr/bin/alertmanager --config.file=/etc/alertmanager/alertmanager.yml --storage.path=/var/lib/alertmanager $ALERTMANAGER_ARGS
ExecReload=/usr/bin/kill -HUP $MAINPID
WorkingDirectory=/var/lib/alertmanager
Restart=on-failure
NoNewPrivileges=yes
ProtectSystem=strict
ProtectHome=yes
PrivateTmp=yes
PrivateDevices=yes
ReadWritePaths=/var/lib/alertmanager

[Install]
WantedBy=multi-user.target
EOF
}
