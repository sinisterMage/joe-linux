# Not in the book: the newest upstream release, built as its
# .goreleaser.yaml builds it (cgo off, -s -w). The version is a constant in
# cmd/version.go, so no -X stamp is needed.
build() {
    # Keep Go's module and build caches inside the build directory, out of
    # the shared build root's /root; never fetch another Go toolchain.
    export GOPATH="$PWD/.gopath"
    export GOMODCACHE="$PWD/.gopath/pkg/mod"
    export GOCACHE="$PWD/.gocache"
    export GOTOOLCHAIN=local GOTELEMETRY=off
    export GOFLAGS="-mod=readonly -trimpath -buildmode=pie -modcacherw"
    export CGO_ENABLED=0
    go build -ldflags "-s -w" -o yq .

    # Shell completions, generated by yq itself.
    local shell
    for shell in bash zsh fish; do
        ./yq completion "$shell" > "yq.$shell"
    done

    tar -xzf "$SOURCES/yq-4.54.3-man-page.tar.gz" --no-same-owner yq.1
}

package() {
    install -Dm755 yq "$DESTDIR/usr/bin/yq"
    install -Dm644 yq.1 "$DESTDIR/usr/share/man/man1/yq.1"
    install -Dm644 yq.bash "$DESTDIR/usr/share/bash-completion/completions/yq"
    install -Dm644 yq.zsh "$DESTDIR/usr/share/zsh/site-functions/_yq"
    install -Dm644 yq.fish "$DESTDIR/usr/share/fish/vendor_completions.d/yq.fish"
}
