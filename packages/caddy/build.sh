# Not in the book: the newest upstream release, built as upstream's
# .goreleaser.yml builds the release binaries, from the vendored buildable
# artifact, so nothing is downloaded. Caddy is a dependency of that module,
# so the version it reports (caddy version) comes from the build
# information Go records: v2.11.9.

unpack() {
    # The artifact's files are at the top of the archive.
    tar -xf "$SOURCES/caddy-2.11.9-buildable-artifact.tar.gz" --no-same-owner --no-same-permissions
    mkdir dist
    tar -xf "$SOURCES/caddy-dist-2.11.9.tar.gz" -C dist --strip-components=1 --no-same-owner --no-same-permissions
}

build() {
    # Keep Go's caches inside the build directory, out of the shared build
    # root's /root; never fetch another Go toolchain.
    export GOPATH="$PWD/.gopath"
    export GOMODCACHE="$PWD/.gopath/pkg/mod"
    export GOCACHE="$PWD/.gocache"
    export GOTOOLCHAIN=local GOTELEMETRY=off GOPROXY=off
    export GOFLAGS="-mod=vendor -trimpath -buildmode=pie"
    export CGO_ENABLED=0
    # Upstream's standard modules and build tags: the tags leave out the
    # Badger, MySQL and PostgreSQL back ends of smallstep's nosql library
    # (storage for the built-in ACME server), as the release binaries do.
    go build -tags nobadger,nomysql,nopgx -ldflags "-s -w" -o caddy .

    # The manual pages and completions, generated by caddy itself as
    # upstream's release and RPM spec do.
    mkdir man
    ./caddy manpage --directory man
    ./caddy completion bash > caddy.bash
    ./caddy completion zsh > _caddy
    ./caddy completion fish > caddy.fish
}

package() {
    install -Dm755 caddy "$DESTDIR/usr/bin/caddy"
    install -d "$DESTDIR/usr/share/man/man8"
    install -m644 man/*.8 "$DESTDIR/usr/share/man/man8/"
    install -Dm644 caddy.bash "$DESTDIR/usr/share/bash-completion/completions/caddy"
    install -Dm644 _caddy "$DESTDIR/usr/share/zsh/site-functions/_caddy"
    install -Dm644 caddy.fish "$DESTDIR/usr/share/fish/vendor_completions.d/caddy.fish"

    # Upstream's default site (:80, the welcome page in /usr/share/caddy)
    # and its two units: caddy.service runs the Caddyfile, caddy-api.service
    # keeps a configuration made through the admin API. Neither is enabled.
    install -Dm644 dist/config/Caddyfile "$DESTDIR/etc/caddy/Caddyfile"
    install -Dm644 dist/welcome/index.html "$DESTDIR/usr/share/caddy/index.html"
    install -Dm644 dist/init/caddy.service "$DESTDIR/usr/lib/systemd/system/caddy.service"
    install -Dm644 dist/init/caddy-api.service "$DESTDIR/usr/lib/systemd/system/caddy-api.service"

    # Upstream's account (dist/init/caddy.sysusers) with a fixed id. Caddy
    # keeps its certificates and autosaved configuration under its home,
    # /var/lib/caddy (~/.local/share/caddy, ~/.config/caddy), which
    # every deployment shares.
    install -d "$DESTDIR/usr/lib/sysusers.d" "$DESTDIR/usr/lib/tmpfiles.d"
    cat > "$DESTDIR/usr/lib/sysusers.d/caddy.conf" << "EOT"
g caddy 46
u caddy 46:46 "Caddy web server" /var/lib/caddy /usr/bin/false
EOT
    cat > "$DESTDIR/usr/lib/tmpfiles.d/caddy.conf" << "EOT"
d /var/lib/caddy 0750 caddy caddy -
EOT
}
