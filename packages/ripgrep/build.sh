# Not in the book: the newest upstream release, built with cargo as its
# README describes, with the pcre2 feature. Upstream publishes no checksum
# for the source archive.
build() {
    # Keep cargo's registry and download cache inside the build directory
    # rather than in root's home in the shared build root.
    export CARGO_HOME="$PWD/.cargo-home"
    # PCRE2_SYS_STATIC=0: link the system libpcre2-8 that pkg-config finds
    # rather than building the copy inside the pcre2-sys crate.
    export PCRE2_SYS_STATIC=0
    # --locked: build exactly the crate versions in upstream's Cargo.lock.
    cargo build --release --locked --features pcre2

    # The manual page and shell completions, generated by rg itself as
    # upstream's release workflow does.
    local rg=target/release/rg
    "$rg" --generate man > rg.1
    "$rg" --generate complete-bash > rg.bash
    "$rg" --generate complete-zsh > _rg
    "$rg" --generate complete-fish > rg.fish
}

package() {
    install -Dm755 target/release/rg "$DESTDIR/usr/bin/rg"
    install -Dm644 rg.1 "$DESTDIR/usr/share/man/man1/rg.1"
    install -Dm644 rg.bash "$DESTDIR/usr/share/bash-completion/completions/rg"
    install -Dm644 _rg "$DESTDIR/usr/share/zsh/site-functions/_rg"
    install -Dm644 rg.fish "$DESTDIR/usr/share/fish/vendor_completions.d/rg.fish"
}
